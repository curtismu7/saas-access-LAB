import { useEffect, useMemo, useState } from "react";
import { postJson, putJson } from "../api";
import { mins, t } from "../fmt";
import { visible } from "../safeText";
import { ClaimTag, SourceTag, useSeq } from "./Bits";
import PolicyEditor from "./PolicyEditor";

const roleLabel = (story, id) => story.roles.find((r) => r.id === id)?.text || id;

function Chain({ story, preview }) {
  if (!preview) return <p className="muted">Working out the approval chain...</p>;
  if (preview.error && !preview.routing.length) return <div className="field-error" role="alert" data-testid="preview-error">{visible(preview.error.detail)}</div>;
  return (
    <div data-testid="preview-chain">
      <p className="lesson" data-testid="preview-auto">{preview.autoApprove ? "The policy approves this request automatically: no approver is needed, and the decision is recorded as made by the policy." : `Needs ${preview.routing.length} approval level(s). The approval window is ${mins(preview.windowMin)}; if approved now, access ends ${t(preview.expiresIfApprovedNow)} UTC.`}</p>
      {!preview.autoApprove && (
        <div className="scroll"><table className="tbl tbl--wide">
          <caption>Approval chain <SourceTag source="reading" /></caption>
          <thead><tr><th>Level</th><th>Role</th><th>Approvals</th><th>Routed to</th></tr></thead>
          <tbody>{preview.routing.map((r) => (
            <tr key={r.level}><td>{r.level + 1}</td><td>{r.role}<div className="muted">{roleLabel(story, r.role)}</div></td><td>{r.required}</td>
              <td>{r.candidates.map((c) => <span key={c.id} className="tag" data-state={c.allowed ? "ok" : "bad"}>{c.id}{c.allowed ? " (can approve)" : ` (cannot: ${c.reason})`}</span>)}</td></tr>
          ))}</tbody>
        </table></div>
      )}
      {preview.error && <div className="field-error" role="alert" data-testid="preview-error">{visible(preview.error.detail)}</div>}
    </div>
  );
}

function Scenarios({ lab, scenarioId, setScenarioId }) {
  const sc = lab.scenario;
  return (
    <section className="panel" data-testid="scenarios">
      <h2 className="panel__title">Scripted scenarios <ClaimTag /></h2>
      <p className="muted">Mock mode reads six scenarios generated by running the lab's own engine. Each is a list of steps; the tabs show the state at the end. Switch to Live to act yourself.</p>
      <div className="seg" role="group" aria-label="Scenario">
        {lab.scenarios.map((s) => <button key={s.id} type="button" aria-pressed={sc?.id === s.id} onClick={() => setScenarioId(s.id)} data-testid={`scenario-${s.id}`}>{s.title}</button>)}
      </div>
      {sc && (
        <>
          <p className="lesson">{sc.say}</p>
          <ol className="plain" data-testid="scenario-steps">
            {sc.steps.map((st, i) => (
              <li key={i}>{st.say ? `${visible(st.say)} ` : ""}<span className="tag" data-state={st.result.ok ? "ok" : "bad"}>{st.op}: {st.result.ok ? "done" : `refused (${st.result.code})`}</span>{!st.result.ok && <span className="muted"> {visible(st.result.detail)}</span>}</li>
            ))}
          </ol>
        </>
      )}
    </section>
  );
}

export default function RequestTab({ story, mode, vertical, lab, scenarioId, setScenarioId }) {
  const state = lab.state;
  const eng = story.cast.castEngineer;
  const [f, setF] = useState({ platform: "github", resource: "gh-repo-core", level: "write", duration: "60", subjectKind: "human", subjectId: eng, requestedBy: eng, policyId: "", reason: "" });
  const [preview, setPreview] = useState(null);
  const [message, setMessage] = useState(null);
  const [policyErrors, setPolicyErrors] = useState([]);
  const run = useSeq();

  const platform = story.platforms.find((p) => p.id === f.platform);
  const resource = platform.resources.find((r) => r.id === f.resource) || platform.resources[0];
  const people = (state?.roster || []).filter((p) => p.kind === f.subjectKind);
  const policies = useMemo(() => (state?.policies || []).filter((p) => p.platform === f.platform && p.resources.includes(resource.id) && !p.retired), [state, f.platform, resource.id]);
  // Unless the visitor picked one, the first policy that can grant this level for this long; failing that, the first that can grant the level.
  const rank = (l) => resource.levels.indexOf(l);
  const dur = Number(f.duration);
  const policy = policies.find((p) => p.id === f.policyId) || policies.find((p) => rank(f.level) <= rank(p.maxLevel) && dur <= p.maxDurationMin) || policies.find((p) => rank(f.level) <= rank(p.maxLevel)) || policies[0] || null;
  const set = (patch) => setF((cur) => ({ ...cur, ...patch }));

  const pickPlatform = (id) => { const p = story.platforms.find((x) => x.id === id); const r = p.resources[0]; set({ platform: id, resource: r.id, level: r.levels[0], policyId: "" }); };
  const pickResource = (id) => { const r = platform.resources.find((x) => x.id === id); set({ resource: id, level: r.levels.includes(f.level) ? f.level : r.levels[0], policyId: "" }); };
  const pickKind = (k) => { const first = (state?.roster || []).find((p) => p.kind === k); set({ subjectKind: k, subjectId: first.id, requestedBy: first.id }); };

  const body = useMemo(() => ({ requestedBy: f.requestedBy, subjectKind: f.subjectKind, subjectId: f.subjectId, platform: f.platform, resource: resource.id, level: f.level, durationMin: f.duration === "" ? null : Number(f.duration), policyId: policy?.id ?? null, reason: f.reason }), [f, resource.id, policy]);

  // The approval chain preview: the same checks and routing as a real request, creating nothing. A late answer never overwrites a newer one.
  useEffect(() => {
    if (!state) return;
    setPreview(null);
    const mine = run();
    postJson("/api/preview", { mode, vertical, request: body }).then((r) => { if (mine()) setPreview(r.body?.preview || { ok: false, error: { detail: "The preview failed." }, routing: [] }); });
  }, [mode, vertical, body, state?.policies, state?.roster]); // eslint-disable-line react-hooks/exhaustive-deps

  const submit = async () => {
    setMessage(null);
    const r = await lab.act("POST", "/api/requests", { request: body });
    setMessage(r.ok ? { ok: true, text: `Request ${r.body?.result?.requestId} is ${r.body?.result?.status}${r.body?.result?.grantId ? ` (grant ${r.body.result.grantId})` : ""}.` } : { ok: false, text: r.body?.detail || r.body?.error || "refused" });
  };
  const savePolicy = async (draft) => {
    set({ policyId: policy.id }); // keep editing this policy: a saved edit must not make the picker jump to another one
    const r = await lab.act("PUT", `/api/policies/${policy.id}`, { policy: draft });
    setPolicyErrors(r.ok ? [] : (r.body?.errors || [r.body?.detail || "refused"]));
  };
  const retire = async () => { await lab.act("POST", `/api/policies/${policy.id}/retire`, {}); set({ policyId: "" }); setPolicyErrors([]); };

  if (!state) return <p className="muted">Loading...</p>;
  const canSubmit = mode === "live" && !lab.busy && preview?.ok;
  return (
    <div className="stack">
      {mode === "mock" && <Scenarios lab={lab} scenarioId={scenarioId} setScenarioId={setScenarioId} />}
      <div className="cols">
        <section className="panel" data-testid="request-form">
          <h2 className="panel__title">Request access <ClaimTag /></h2>
          <p className="muted">{mode === "live" ? "Pick what to ask for. The approval chain is worked out before anything is created." : "Mock is read-only: the form and the chain preview work, but nothing is created. Switch to Live to submit."}</p>
          <div className="filters">
            <label>Platform
              <select value={f.platform} onChange={(e) => pickPlatform(e.target.value)} data-testid="platform">{story.platforms.map((p) => <option key={p.id} value={p.id}>{p.name}</option>)}</select>
            </label>
            <label>Resource
              <select value={resource.id} onChange={(e) => pickResource(e.target.value)} data-testid="resource">{platform.resources.map((r) => <option key={r.id} value={r.id}>{r.name} ({r.kind})</option>)}</select>
            </label>
            <label>Level
              <select value={f.level} onChange={(e) => set({ level: e.target.value })} data-testid="level">{resource.levels.map((l) => <option key={l}>{l}</option>)}</select>
            </label>
            <label>Duration (minutes)
              <input type="number" min="1" value={f.duration} onChange={(e) => set({ duration: e.target.value })} data-testid="duration" />
            </label>
          </div>
          <div className="seg" role="group" aria-label="Duration presets">
            {[15, 60, 240, 480].map((m) => <button key={m} type="button" aria-pressed={String(m) === f.duration} onClick={() => set({ duration: String(m) })} data-testid={`dur-${m}`}>{mins(m)}</button>)}
          </div>
          <div className="filters">
            <label>Subject is a
              <select value={f.subjectKind} onChange={(e) => pickKind(e.target.value)} data-testid="subject-kind"><option value="human">human</option><option value="agent">agent</option></select>
            </label>
            <label>Subject
              <select value={f.subjectId} onChange={(e) => set({ subjectId: e.target.value, requestedBy: e.target.value })} data-testid="subject">{people.map((p) => <option key={p.id} value={p.id}>{p.id}</option>)}</select>
            </label>
            <label>Requested by
              <select value={f.requestedBy} onChange={(e) => set({ requestedBy: e.target.value })} data-testid="requested-by">{(state.roster).map((p) => <option key={p.id} value={p.id}>{p.id} ({p.kind})</option>)}</select>
            </label>
            <label>Policy
              <select value={policy?.id || ""} onChange={(e) => set({ policyId: e.target.value })} data-testid="policy">{policies.length ? policies.map((p) => <option key={p.id} value={p.id}>{p.name}</option>) : <option value="">no policy covers this</option>}</select>
            </label>
          </div>
          <label>Reason (credential-shaped values are masked; a heuristic, not every secret has a recognisable shape)
            <textarea rows={2} maxLength={300} value={f.reason} onChange={(e) => set({ reason: e.target.value })} data-testid="reason" />
          </label>
          <div className="seg">
            <button type="button" className="primary" disabled={!canSubmit} onClick={submit} data-testid="submit-request">Submit the request</button>
          </div>
          {message && <p className={message.ok ? "lesson" : "field-error"} role={message.ok ? "status" : "alert"} data-testid="request-message">{visible(message.text)}</p>}
        </section>
        <section className="panel">
          <h2 className="panel__title">What will happen</h2>
          <Chain story={story} preview={preview} />
        </section>
      </div>
      {policy && <PolicyEditor policy={policy} levels={resource.levels} roles={story.roles} readOnly={mode !== "live"} busy={lab.busy} onSave={savePolicy} onRetire={retire} errors={policyErrors} />}
    </div>
  );
}
